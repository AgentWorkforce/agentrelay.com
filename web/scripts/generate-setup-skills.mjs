#!/usr/bin/env node
// Generates web/lib/generated/setup-skills.ts, the bundled text that
// /signup/agent/teams and /signup/agent/flows render (Workers have no
// filesystem). The skills are written in AgentWorkforce/skills and installed
// here by prpm: prpm.lock pins each package, and `prpm install` writes its
// SKILL.md under .claude/skills/. Nothing here is edited by hand.
//
//   prpm install @agent-relay/<skill> --as claude -y   # add a skill
//   prpm update                                        # move the pins
//   node web/scripts/generate-setup-skills.mjs         # regenerate the module
//   node web/scripts/generate-setup-skills.mjs --check # fail on drift
//
// CI also runs `prpm install --frozen-lockfile` and fails when that changes
// .claude/skills or prpm.lock, which proves the installed copies are current.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const repoRoot = new URL('../../', import.meta.url);
const lockUrl = new URL('prpm.lock', repoRoot);
const generatedUrl = new URL('../lib/generated/setup-skills.ts', import.meta.url);

/** The skills the signup guides render, in AgentWorkforce/skills' @agent-relay scope. */
export const SETUP_SKILL_NAMES = [
  'signing-in-to-agent-relay-cloud',
  'setting-up-agent-relay-desktop',
  'setting-up-agent-relay-sessions',
  'setting-up-agent-relay-flows',
  'writing-relayflows',
];

export function stripFrontmatter(text) {
  const match = /^---\r?\n[\s\S]*?\r?\n---(?:\r?\n)+/.exec(text);
  if (!match) throw new Error('SKILL.md is missing YAML frontmatter');
  return text.slice(match[0].length);
}

export function renderModule(versions, skills) {
  const banner = '// Generated by web/scripts/generate-setup-skills.mjs from the prpm-installed\n'
    + '// @agent-relay setup skills pinned in prpm.lock. Do not edit.\n';
  return `${banner}export const SETUP_SKILLS_SOURCE = ${JSON.stringify({ registry: 'prpm', packages: versions })} as const;\n\n`
    + `export const SETUP_SKILLS: Readonly<Record<string, string>> = ${JSON.stringify(skills, null, 2)};\n`;
}

/** Reads the pinned version and installed SKILL.md of every setup skill, or names what is missing. */
export async function readInstalledSkills(lockText, readInstalled) {
  const lock = JSON.parse(lockText);
  const versions = {};
  const skills = {};
  const missing = [];
  for (const name of SETUP_SKILL_NAMES) {
    const entry = lock.packages?.[`@agent-relay/${name}#claude`];
    if (!entry || typeof entry.installedPath !== 'string') {
      missing.push(`@agent-relay/${name} is not in prpm.lock`);
      continue;
    }
    const text = await readInstalled(entry.installedPath).catch(() => null);
    if (text === null) {
      missing.push(`${entry.installedPath} is missing (run prpm install)`);
      continue;
    }
    versions[name] = entry.version;
    skills[name] = stripFrontmatter(text);
  }
  if (missing.length) throw new Error(`Setup skills are not installed:\n${missing.map(line => `  ${line}`).join('\n')}`);
  return { versions, skills };
}

async function main() {
  const check = process.argv.includes('--check');
  const { versions, skills } = await readInstalledSkills(
    await readFile(lockUrl, 'utf8'),
    path => readFile(new URL(path, repoRoot), 'utf8'),
  );
  const expected = renderModule(versions, skills);
  if (check) {
    const existing = await readFile(generatedUrl, 'utf8').catch(() => null);
    if (existing !== expected) {
      console.error(`${generatedUrl.pathname} does not match the prpm-installed setup skills.`);
      console.error('Run node web/scripts/generate-setup-skills.mjs; never edit the generated module by hand.');
      process.exit(1);
    }
    console.log(`Setup skills match prpm.lock (${Object.entries(versions).map(([name, version]) => `${name}@${version}`).join(', ')}).`);
    return;
  }
  await mkdir(new URL('.', generatedUrl), { recursive: true });
  await writeFile(generatedUrl, expected);
  console.log(`Generated the setup skills module from prpm.lock (${SETUP_SKILL_NAMES.length} skills).`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    await main();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
