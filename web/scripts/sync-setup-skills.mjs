#!/usr/bin/env node
// Vendors the Agent Relay setup skills that /signup/agent/teams and
// /signup/agent/flows render. The single source of truth is the public
// AgentWorkforce/skills repository at the commit pinned in
// web/content/setup-skills/SOURCE.json; nothing here is edited by hand.
//
//   node web/scripts/sync-setup-skills.mjs          # fetch the pin, rewrite the copies
//   node web/scripts/sync-setup-skills.mjs --check  # fail when the copies differ from the pin
//
// To move the pin, change "commit" in SOURCE.json and run without --check.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const contentDir = new URL('../content/setup-skills/', import.meta.url);
const sourceUrl = new URL('SOURCE.json', contentDir);
const generatedUrl = new URL('../lib/generated/setup-skills.ts', import.meta.url);
const SHA = /^[0-9a-f]{40}$/;
const NAME = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function stripFrontmatter(text) {
  const match = /^---\n[\s\S]*?\n---\n+/.exec(text);
  if (!match) throw new Error('SKILL.md is missing YAML frontmatter');
  return text.slice(match[0].length);
}

export function renderModule(source, skills) {
  const banner = '// Generated by web/scripts/sync-setup-skills.mjs from the pinned\n'
    + '// AgentWorkforce/skills commit in web/content/setup-skills/SOURCE.json. Do not edit.\n';
  return `${banner}export const SETUP_SKILLS_SOURCE = ${JSON.stringify({ repository: source.repository, commit: source.commit })} as const;\n\n`
    + `export const SETUP_SKILLS: Readonly<Record<string, string>> = ${JSON.stringify(skills, null, 2)};\n`;
}

async function readSource() {
  const source = JSON.parse(await readFile(sourceUrl, 'utf8'));
  if (source.repository !== 'AgentWorkforce/skills') throw new Error('SOURCE.json repository must be AgentWorkforce/skills');
  if (!SHA.test(source.commit ?? '')) throw new Error('SOURCE.json commit must be a full 40-character commit SHA');
  if (!Array.isArray(source.skills) || source.skills.length === 0 || !source.skills.every(name => NAME.test(name))) {
    throw new Error('SOURCE.json skills must be a non-empty list of skill directory names');
  }
  return source;
}

async function fetchSkill(source, name) {
  const url = `https://raw.githubusercontent.com/${source.repository}/${source.commit}/skills/${name}/SKILL.md`;
  for (let attempt = 1; ; attempt += 1) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      return stripFrontmatter(await response.text());
    } catch (error) {
      if (attempt >= 3) throw new Error(`Could not fetch ${url}: ${error.message}`);
      await new Promise(resolve => setTimeout(resolve, attempt * 2000));
    }
  }
}

async function main() {
  const check = process.argv.includes('--check');
  const source = await readSource();
  const skills = Object.fromEntries(await Promise.all(source.skills.map(async name => [name, await fetchSkill(source, name)])));
  const expected = new Map(source.skills.map(name => [new URL(`${name}.md`, contentDir), skills[name]]));
  expected.set(generatedUrl, renderModule(source, skills));

  if (check) {
    const stale = [];
    for (const [url, text] of expected) {
      const existing = await readFile(url, 'utf8').catch(() => null);
      if (existing !== text) stale.push(url.pathname);
    }
    if (stale.length) {
      console.error(`Setup skills differ from AgentWorkforce/skills@${source.commit}:\n${stale.map(path => `  ${path}`).join('\n')}`);
      console.error('Run node web/scripts/sync-setup-skills.mjs to re-vendor them; never edit the copies by hand.');
      process.exit(1);
    }
    console.log(`Setup skills match AgentWorkforce/skills@${source.commit} (${source.skills.join(', ')}).`);
    return;
  }
  await mkdir(new URL('.', generatedUrl), { recursive: true });
  for (const [url, text] of expected) await writeFile(url, text);
  console.log(`Vendored ${source.skills.length} setup skills from AgentWorkforce/skills@${source.commit}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
